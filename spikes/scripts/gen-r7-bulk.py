#!/usr/bin/env python3
"""Generate the R7 bulk suites: N trivial unit tests (classes of 10 facts) for xUnit v3 and TUnit, to measure
how run time grows with test count. Usage: gen-r7-bulk.py N"""
import sys
n = int(sys.argv[1]); classes = n // 10
x = ["// Generated by scripts/gen-r7-bulk.py; do not edit.", "using Xunit;", "namespace Spike.R7.XunitBulk;"]
t = ["// Generated by scripts/gen-r7-bulk.py; do not edit.", "using TUnit.Assertions;", "using TUnit.Assertions.Extensions;",
     "using TUnit.Core;", "namespace Spike.R7.TUnitBulk;"]
for c in range(classes):
    x.append(f'[Trait("Lane", "unit")] public sealed class Bulk{c:04d} {{')
    t.append(f'[Property("Lane", "unit")] public sealed class Bulk{c:04d} {{')
    for f in range(10):
        x.append(f'  [Fact] public void T{f}() => Assert.Equal({c * 10 + f}, Spike.R7.Budget.Remaining({c * 10 + f}, 0));')
        t.append(f'  [Test] public async Task T{f}() => await Assert.That(Spike.R7.Budget.Remaining({c * 10 + f}, 0)).IsEqualTo({c * 10 + f});')
    x.append("}"); t.append("}")
open("r7-tests/XunitV3.Bulk/Generated.cs", "w").write("\n".join(x) + "\n")
open("r7-tests/TUnit.Bulk/Generated.cs", "w").write("\n".join(t) + "\n")
print(f"generated {classes * 10} tests per framework")
